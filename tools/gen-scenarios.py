#!/usr/bin/env python3
"""Writes the benchmark scenarios (format: engine/clr/src/autoplay.rs) into scenarios/.
   python tools/gen-scenarios.py [out dir]   -- deterministic: the same files every time."""
import random, sys, os

OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "scenarios")
os.makedirs(OUT, exist_ok=True)
S = 30  # ticks per second of game time

def write(name, lines):
    with open(os.path.join(OUT, name + ".txt"), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")

BOOT = ["0 mark boot", "0 click Create New Game", "20 click Slot 1", "40 click Create New Game", "150 click PLAY"]
HEAD = ["# Generated by tools/gen-scenarios.py; do not edit by hand."]
MENUS = [0, 5, 17, 18, 6, 14, 8, 4, 3, 13, 15, 23, 12, 26, 21, 10, 11]
BTN = ["Cap", "+", "-", "1/2", "1/4"]

def visit(t, m, dwell, rnd):
    """One menu visit: switch, then buttons, D-pad moves, a tap and a stick scroll, then idle."""
    L = [f"{t} mark menu{m}", f"{t} menu {m}"]
    t += S
    for _ in range(3):
        L.append(f"{t} click {rnd.choice(BTN)}")
        t += S // 2
    L.append(f"{t} pad {rnd.choice(['dd', 'ddr', 'ul', 'rrd'])}a")
    t += S
    L.append(f"{t} touch {rnd.randint(300, 940)} {rnd.randint(60, 500)}")
    t += S // 2
    L.append(f"{t} scroll 0 {rnd.choice([-1, 1])}")
    return L, t + dwell

# 30 minutes of play: 5 laps over the main menus, a digest check and a Save page visit per lap.
rnd = random.Random(1)
L, t = HEAD + BOOT, 400
for lap in range(5):
    for m in MENUS:
        v, t = visit(t, m, 8 * S, rnd)
        L += v
    L += [f"{t} mark save-page", f"{t} click Save Game", f"{t + S} pad b", f"{t + 2 * S} check lap{lap}"]
    t += 3 * S
L.append(f"{t} end")
write("session", L)

# Tour: every one of the 58 menus for 5 s, no buttons (layout and draw cost per screen).
L, t = HEAD + BOOT, 400
for m in range(58):
    L += [f"{t} mark menu{m}", f"{t} menu {m}", f"{t + S} pad d"]
    t += 5 * S
L += [f"{t} check tour", f"{t + 1} end"]
write("tour", L)

# Look: a screenshot of the main menus (bench/shotN.tga on the console), to check by eye that drawing is right after a host change.
L, t = HEAD + BOOT, 400
for m in MENUS:
    L += [f"{t} mark menu{m}", f"{t} menu {m}", f"{t + 2 * S} shot"]
    t += 4 * S
L += [f"{t} click Save Game", f"{t + 2 * S} shot", f"{t + 3 * S} pad b", f"{t + 4 * S} end"]
write("look", L)

# Late: the same tour starting from an advanced save (FIXTURE=<save> tools/vita-cycle.sh late late-tour): Load Autosave, then every menu.
LATE_BOOT = ["0 mark boot", "0 click Load Autosave", "120 click On To The Game!"]
L, t = HEAD + LATE_BOOT, 400
for m in range(58):
    L += [f"{t} mark menu{m}", f"{t} menu {m}", f"{t + S} pad d"]
    t += 5 * S
L += [f"{t} check late", f"{t + 1} end"]
write("late", L)

# Monkey: seeded random walk for 2 hours; replay one seed on PC to understand a spike.
SEED = 7
rnd = random.Random(SEED)
L, t = HEAD + [f"# seed {SEED}"] + BOOT, 400
while t < 2 * 3600 * S:
    r = rnd.random()
    if r < 0.25:
        L += [f"{t} mark menu", f"{t} menu {rnd.randrange(58)}"]
    elif r < 0.55:
        L.append(f"{t} click {rnd.choice(BTN)}")
    elif r < 0.8:
        L.append(f"{t} pad {rnd.choice('udlrab')}")
    elif r < 0.95:
        L.append(f"{t} touch {rnd.randint(0, 959)} {rnd.randint(0, 543)}")
    else:
        L.append(f"{t} scroll {rnd.choice([-1, 0, 1])} {rnd.choice([-1, 1])}")
    t += rnd.randint(5, 45)
    if t % 1500 < 45:
        L.append(f"{t} check monkey{t}")
L.append(f"{t} end")
write("monkey", L)
